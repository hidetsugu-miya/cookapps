/// The emoji of a Slack name that the `emojis` crate does not know.
pub fn get(name: &str) -> Option<&'static str> {
    EMOJI
        .binary_search_by(|(n, _)| n.cmp(&name))
        .ok()
        .map(|i| EMOJI[i].1)
}
